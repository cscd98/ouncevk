"""Generates the Vulkan API functions for a static Horizon build.

Horizon has no Vulkan loader. A program links the driver statically and
calls vkCreateInstance and the other API functions by name. This script
writes one C file that defines these functions. Each function gets the
driver function from vk_icdGetInstanceProcAddr when it is first called, and
then calls it.

The file defines the commands of Vulkan 1.0 to 1.4 and of the extensions in
EXPORTED_EXTENSIONS. A desktop Vulkan loader also exports only the core
commands and the window-system commands. A program gets the commands of
other extensions with vkGetInstanceProcAddr or vkGetDeviceProcAddr.

The driver gives no function for these commands, because a loader usually
supplies them:
- vkEnumerateInstanceLayerProperties and vkEnumerateDeviceLayerProperties
  report zero layers.

Usage:
  nvk_horizon_exports_gen.py --xml vk.xml --import-path DIR --out FILE
"""
import argparse
import sys

# The extensions whose commands are exported, in addition to core Vulkan.
EXPORTED_EXTENSIONS = (
    "VK_KHR_surface",
    "VK_KHR_swapchain",
    "VK_NN_vi_surface",
)

# The newest core version whose commands are exported.
EXPORTED_CORE_VERSION = (1, 4)

# Commands that this file implements itself, with no driver function.
LOCAL_COMMANDS = (
    "vkEnumerateInstanceLayerProperties",
    "vkEnumerateDeviceLayerProperties",
)

# Commands that record or forget the instance used for look-ups.
INSTANCE_COMMANDS = (
    "vkCreateInstance",
    "vkDestroyInstance",
    "vkGetInstanceProcAddr",
)

HEADER = """\
/* SPDX-License-Identifier: MIT
 * Generated by nvk_horizon_exports_gen.py. Do not edit.
 *
 * The Vulkan API functions for a static Horizon build. See the script for
 * the design. */
#define VK_USE_PLATFORM_VI_NN 1
#undef VK_NO_PROTOTYPES
#include <string.h>
#include <vulkan/vulkan.h>

#include "util/u_atomic.h"

#define NVK_EXPORT __attribute__((visibility("default")))

VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL
vk_icdGetInstanceProcAddr(VkInstance instance, const char *name);

/* The instance for look-ups: the instance that the program created last.
 * A function that the driver supplies is the same for all instances, so a
 * function pointer that a look-up returns stays valid. */
static VkInstance export_instance;

/* Gets the driver function NAME and keeps it in *SLOT. A look-up that
 * returns NULL is not kept: the next call tries again. */
static PFN_vkVoidFunction
export_resolve(PFN_vkVoidFunction *slot, const char *name)
{
   PFN_vkVoidFunction function = p_atomic_read(slot);
   if (function != NULL)
      return function;

   function = vk_icdGetInstanceProcAddr(p_atomic_read(&export_instance), name);
   if (function != NULL)
      p_atomic_set(slot, function);
   return function;
}

NVK_EXPORT VKAPI_ATTR VkResult VKAPI_CALL
vkEnumerateInstanceLayerProperties(uint32_t *pPropertyCount,
                                   VkLayerProperties *pProperties)
{
   (void)pProperties;
   *pPropertyCount = 0;
   return VK_SUCCESS;
}

NVK_EXPORT VKAPI_ATTR VkResult VKAPI_CALL
vkEnumerateDeviceLayerProperties(VkPhysicalDevice physicalDevice,
                                 uint32_t *pPropertyCount,
                                 VkLayerProperties *pProperties)
{
   (void)physicalDevice;
   (void)pProperties;
   *pPropertyCount = 0;
   return VK_SUCCESS;
}

NVK_EXPORT VKAPI_ATTR VkResult VKAPI_CALL
vkCreateInstance(const VkInstanceCreateInfo *pCreateInfo,
                 const VkAllocationCallbacks *pAllocator,
                 VkInstance *pInstance)
{
   /* This file is the loader: it has no layers. */
   if (pCreateInfo != NULL && pCreateInfo->enabledLayerCount > 0)
      return VK_ERROR_LAYER_NOT_PRESENT;
   static PFN_vkVoidFunction slot;
   PFN_vkCreateInstance function =
      (PFN_vkCreateInstance)export_resolve(&slot, "vkCreateInstance");
   VkResult result = function(pCreateInfo, pAllocator, pInstance);
   if (result == VK_SUCCESS)
      p_atomic_set(&export_instance, *pInstance);
   return result;
}

NVK_EXPORT VKAPI_ATTR void VKAPI_CALL
vkDestroyInstance(VkInstance instance, const VkAllocationCallbacks *pAllocator)
{
   static PFN_vkVoidFunction slot;
   PFN_vkDestroyInstance function =
      (PFN_vkDestroyInstance)export_resolve(&slot, "vkDestroyInstance");
   (void)p_atomic_cmpxchg(&export_instance, instance, VK_NULL_HANDLE);
   if (function != NULL)
      function(instance, pAllocator);
}

/* Gives the functions of this file for the commands that this file must
 * handle. The other commands go to the driver. */
NVK_EXPORT VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL
vkGetInstanceProcAddr(VkInstance instance, const char *pName)
{
   if (pName == NULL)
      return NULL;
   /* Global commands. With a NULL instance, only these are valid. */
   if (strcmp(pName, "vkCreateInstance") == 0)
      return (PFN_vkVoidFunction)vkCreateInstance;
   if (strcmp(pName, "vkGetInstanceProcAddr") == 0)
      return (PFN_vkVoidFunction)vkGetInstanceProcAddr;
   if (strcmp(pName, "vkEnumerateInstanceLayerProperties") == 0)
      return (PFN_vkVoidFunction)vkEnumerateInstanceLayerProperties;
   if (instance == VK_NULL_HANDLE)
      return vk_icdGetInstanceProcAddr(instance, pName);
   /* Instance-level commands that this file handles. */
   if (strcmp(pName, "vkDestroyInstance") == 0)
      return (PFN_vkVoidFunction)vkDestroyInstance;
   if (strcmp(pName, "vkEnumerateDeviceLayerProperties") == 0)
      return (PFN_vkVoidFunction)vkEnumerateDeviceLayerProperties;
   return vk_icdGetInstanceProcAddr(instance, pName);
}
"""

FUNCTION = """\

NVK_EXPORT VKAPI_ATTR {return_type} VKAPI_CALL
vk{name}({params})
{{
   static PFN_vkVoidFunction slot;
   PFN_vk{name} function =
      (PFN_vk{name})export_resolve(&slot, "vk{name}");
   {call}function({args});
}}
"""


def is_exported(entrypoint):
    """True for a command of an exported core version or extension."""
    version = entrypoint.core_version
    if version is not None:
        return (version.major, version.minor) <= EXPORTED_CORE_VERSION
    return any(extension.name in EXPORTED_EXTENSIONS
               for extension in entrypoint.extensions)


def function_source(entrypoint):
    """The C definition of one exported command."""
    return FUNCTION.format(
        return_type=entrypoint.return_type,
        name=entrypoint.name,
        params=entrypoint.decl_params(),
        call="" if entrypoint.return_type == "void" else "return ",
        args=entrypoint.call_params())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--xml", required=True)
    parser.add_argument("--import-path", required=True,
                        help="the directory of vk_entrypoints.py")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    sys.path.insert(0, args.import_path)
    from vk_entrypoints import get_entrypoints_from_xml

    handled = set(LOCAL_COMMANDS) | set(INSTANCE_COMMANDS)
    source = [HEADER]
    for entrypoint in get_entrypoints_from_xml([args.xml], beta=False):
        if not is_exported(entrypoint):
            continue
        if "vk" + entrypoint.name in handled:
            continue
        source.append(function_source(entrypoint))

    with open(args.out, "w", encoding="utf-8") as out:
        out.write("".join(source))


if __name__ == "__main__":
    main()
